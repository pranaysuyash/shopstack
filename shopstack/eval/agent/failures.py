"""Stable failure taxonomy for scenario-level agent evaluation."""
from __future__ import annotations

from enum import StrEnum


class FailureCode(StrEnum):
    WRONG_TOOL = "WRONG_TOOL"
    MISSING_REQUIRED_TOOL = "MISSING_REQUIRED_TOOL"
    FORBIDDEN_TOOL = "FORBIDDEN_TOOL"
    INVALID_TOOL = "INVALID_TOOL"
    ARG_MISSING = "ARG_MISSING"
    ARG_WRONG_VALUE = "ARG_WRONG_VALUE"
    ARG_WRONG_TYPE = "ARG_WRONG_TYPE"
    UNIT_MISMATCH = "UNIT_MISMATCH"
    EXCESS_TOOL_CALLS = "EXCESS_TOOL_CALLS"
    EXECUTION_ERROR = "EXECUTION_ERROR"
    STATE_MISMATCH = "STATE_MISMATCH"
    CONSTRAINT_VIOLATION = "CONSTRAINT_VIOLATION"
    UNSUPPORTED_ENTITY = "UNSUPPORTED_ENTITY"
    UNNECESSARY_MUTATION = "UNNECESSARY_MUTATION"
    FAILED_TO_CLARIFY = "FAILED_TO_CLARIFY"
    FAILED_TO_ABSTAIN = "FAILED_TO_ABSTAIN"
    PARSE_ERROR = "PARSE_ERROR"
    EMPTY_OUTPUT = "EMPTY_OUTPUT"
    TIMEOUT = "TIMEOUT"
    PROVIDER_UNAVAILABLE = "PROVIDER_UNAVAILABLE"
    FALLBACK_DETECTED = "FALLBACK_DETECTED"
    COST_BUDGET_EXCEEDED = "COST_BUDGET_EXCEEDED"
    LATENCY_BUDGET_EXCEEDED = "LATENCY_BUDGET_EXCEEDED"
    INTERNAL_EVAL_ERROR = "INTERNAL_EVAL_ERROR"


ALL_FAILURE_CODES = {code.value for code in FailureCode}
